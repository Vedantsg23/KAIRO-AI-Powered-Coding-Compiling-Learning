// Runs first in the Vercel build (vercel.json "buildCommand") and prepares two files
// that exist only in the build, never in Git (both are listed in .gitignore):
//
// 1. services/api/app/_build/evidence.key: the key that signs run evidence and
//    Saarthi's fix tokens, so every server instance of this deployment can check
//    what the browser hands back (services/api/app/services/evidence.py). It is
//    random, new for every deployment, and goes only into the Python function's
//    bundle: never into Git, the build log or the web app. A CC_EVIDENCE_SECRET
//    environment variable, when the project sets one, is used instead.
//
// 2. apps/web/.env.vercel: the live site's public settings (the Supabase project
//    URL and publishable key) from infra/vercel/public-settings.json, for the web
//    app's build (`vite build --mode vercel`) and the API's daily keep-alive.
//    Environment variables with the same names still win (Vite and the API both
//    prefer them).
import { randomBytes } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");

// 1. The evidence key.
const keyFile = join(root, "services", "api", "app", "_build", "evidence.key");
if ((process.env.CC_EVIDENCE_SECRET ?? "").trim()) {
  console.log("evidence key: CC_EVIDENCE_SECRET is set, nothing to generate");
} else {
  mkdirSync(dirname(keyFile), { recursive: true });
  writeFileSync(keyFile, `${randomBytes(48).toString("base64url")}\n`);
  console.log("evidence key: generated for this deployment");
}

// 2. The public settings, as an env file for Vite and the API.
const settings = JSON.parse(readFileSync(join(root, "infra", "vercel", "public-settings.json"), "utf8"));
const lines = ["# Generated by infra/vercel/build-keys.mjs from infra/vercel/public-settings.json (public values only)."];
for (const [name, value] of Object.entries(settings)) {
  if (!/^VITE_[A-Z0-9_]+$/.test(name)) continue; // only the web app's public settings
  if (typeof value !== "string" || /[\r\n]/.test(value)) throw new Error(`public-settings.json: ${name} must be one line of text`);
  if (/^sb_secret_/i.test(value) || legacyRole(value) === "service_role") {
    throw new Error(`public-settings.json: ${name} is a secret key; only the publishable key belongs here`);
  }
  lines.push(`${name}=${value}`);
}
writeFileSync(join(root, "apps", "web", ".env.vercel"), `${lines.join("\n")}\n`);
console.log(`public settings: ${lines.length - 1} written for the web app`);

/** The role inside a legacy Supabase key (a JWT: "anon" or "service_role"), or null. */
function legacyRole(value) {
  const parts = value.split(".");
  if (parts.length !== 3 || !value.startsWith("eyJ")) return null;
  try {
    return JSON.parse(Buffer.from(parts[1], "base64url").toString("utf8")).role ?? null;
  } catch {
    return null;
  }
}
